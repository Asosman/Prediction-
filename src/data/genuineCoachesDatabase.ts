/**
 * Normalizes input name for lookup
 */
function cleanKey(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '');
}

/**
 * Strips common generic football club prefixes and suffixes
 */
function stripFootballAffixes(key: string): string {
  return key
    .replace(/^(fc|cf|sc|ac|cd|cs|rc|ssv|tsv|as|us|hb|rfc|fk|sk)_/g, '')
    .replace(/_(fc|cf|sc|ac|cd|cs|afc|club|de_futbol|united_fc|city_fc|1900)$/g, '');
}

