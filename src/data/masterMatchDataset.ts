const BASELINE_TEAM_ELO: Record<string, number> = JSON.parse(JSON.stringify(TEAM_BASE_ELO));

/**
 * Dynamically ingests a newly played match into the active Data Lake
 * and updates dynamic Elo ratings in real-time.
 */
export function ingestMatchRecord(record: Partial<RawMatchRecord> & {
  home_team: string;
  away_team: string;
  date: string;
  home_goals: number;
  away_goals: number;
}): {
  success: boolean;
  new_match_id: string;
  total_records: number;
  elo_update: {
    home_elo: number;
    away_elo: number;
    new_elo_home: number;
    new_elo_away: number;
    elo_change_home: number;
    elo_change_away: number;
  };
} {
  const normHome = record.home_team.toLowerCase().trim().replace(/[^a-z0-9]/g, '_');
  const normAway = record.away_team.toLowerCase().trim().replace(/[^a-z0-9]/g, '_');
  const matchId = record.match_id || `live_ingested_${Date.now()}`;

  // Check if upcoming match can be updated in-place or if new record is pushed
  const existingIdx = RAW_MATCH_RECORDS.findIndex(
    (m) =>
      (m.match_id === matchId) ||
      (!m.is_played &&
        m.home_team.toLowerCase() === record.home_team.toLowerCase() &&
        m.away_team.toLowerCase() === record.away_team.toLowerCase())
  );

  const fullRecord: RawMatchRecord = {
    match_id: matchId,
    date: record.date || new Date().toISOString().split('T')[0],
    season: record.season || '2026/2027',
    league_id: record.league_id || 'epl',
    league_name: record.league_name || 'Premier League',
    home_team_id: normHome,
    home_team: record.home_team,
    away_team_id: normAway,
    away_team: record.away_team,
    home_goals: record.home_goals,
    away_goals: record.away_goals,
    total_goals: record.home_goals + record.away_goals,
    home_shots: record.home_shots ?? (record.home_goals * 5 + 8),
    away_shots: record.away_shots ?? (record.away_goals * 4 + 7),
    total_shots: (record.home_shots ?? (record.home_goals * 5 + 8)) + (record.away_shots ?? (record.away_goals * 4 + 7)),
    home_shots_on_target: record.home_shots_on_target ?? Math.max(record.home_goals, Math.round((record.home_shots ?? 14) * 0.38)),
    away_shots_on_target: record.away_shots_on_target ?? Math.max(record.away_goals, Math.round((record.away_shots ?? 10) * 0.35)),
    total_shots_on_target:
      (record.home_shots_on_target ?? Math.max(record.home_goals, 4)) +
      (record.away_shots_on_target ?? Math.max(record.away_goals, 3)),
    home_xg: record.home_xg ?? Number((record.home_goals * 0.7 + (record.home_shots ?? 14) * 0.08).toFixed(2)),
    away_xg: record.away_xg ?? Number((record.away_goals * 0.7 + (record.away_shots ?? 10) * 0.08).toFixed(2)),
    total_xg: Number(
      (
        (record.home_xg ?? (record.home_goals * 0.7 + (record.home_shots ?? 14) * 0.08)) +
        (record.away_xg ?? (record.away_goals * 0.7 + (record.away_shots ?? 10) * 0.08))
      ).toFixed(2)
    ),
    home_possession: record.home_possession ?? 52,
    away_possession: record.away_possession ?? 48,
    home_corners: record.home_corners ?? 6,
    away_corners: record.away_corners ?? 4,
    home_yellow_cards: record.home_yellow_cards ?? 1,
    away_yellow_cards: record.away_yellow_cards ?? 2,
    known_at: `${record.date}T22:00:00Z`,
    is_played: true,
  };

  if (existingIdx >= 0) {
    RAW_MATCH_RECORDS[existingIdx] = fullRecord;
  } else {
    RAW_MATCH_RECORDS.push(fullRecord);
  }

  // Calculate dynamic Elo update
  const homeElo = TEAM_BASE_ELO[normHome] || 1680;
  const awayElo = TEAM_BASE_ELO[normAway] || 1680;
  const K = 32;

  // Expected outcome (Home has +65 Elo advantage)
  const dr = (homeElo + 65) - awayElo;
  const expectedHome = 1 / (1 + Math.pow(10, -dr / 400));
  
  let actualHome = 0.5;
  if (record.home_goals > record.away_goals) actualHome = 1.0;
  else if (record.home_goals < record.away_goals) actualHome = 0.0;

  // Goal difference multiplier
  const goalDiff = Math.abs(record.home_goals - record.away_goals);
  const gMultiplier = goalDiff <= 1 ? 1.0 : goalDiff === 2 ? 1.5 : 1.75 + (goalDiff - 3) / 8;

  const eloDelta = Math.round(K * gMultiplier * (actualHome - expectedHome));
  TEAM_BASE_ELO[normHome] = homeElo + eloDelta;
  TEAM_BASE_ELO[normAway] = awayElo - eloDelta;

  return {
    success: true,
    new_match_id: matchId,
    total_records: RAW_MATCH_RECORDS.length,
    elo_update: {
      home_elo: TEAM_BASE_ELO[normHome],
      away_elo: TEAM_BASE_ELO[normAway],
      new_elo_home: TEAM_BASE_ELO[normHome],
      new_elo_away: TEAM_BASE_ELO[normAway],
      elo_change_home: eloDelta,
      elo_change_away: -eloDelta,
    },
  };
}

/**
 * Resets dataset and Elo ratings to initial clean state.
 */
export function resetDatasetToBaseline(): void {
  RAW_MATCH_RECORDS.length = 0;
  BASELINE_MATCH_RECORDS.forEach((r) => RAW_MATCH_RECORDS.push(JSON.parse(JSON.stringify(r))));
  Object.keys(TEAM_BASE_ELO).forEach((k) => delete TEAM_BASE_ELO[k]);
  Object.assign(TEAM_BASE_ELO, JSON.parse(JSON.stringify(BASELINE_TEAM_ELO)));
}
